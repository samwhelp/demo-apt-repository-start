#!/usr/bin/env bash


################################################################################
## Environment
################################################################################

set -e						# exit on error
set -o pipefail				# exit on pipeline error
set -u						# treat unset variable as error


################################################################################
## Base Path
################################################################################

BASE_DIR_PATH="$(dirname "$(realpath "${0}")")"




################################################################################
## Init
################################################################################

source "${BASE_DIR_PATH}/init.sh"




################################################################################
## Module
################################################################################

function sys_prepare_package_install () {

	local run_cmd="sudo apt-get install -y --no-install-recommends
		gpg
		apt-utils
		dpkg-dev
		debhelper
	"

	echo ${run_cmd}
	${run_cmd}

}

function mod_prepare_package_install () {

	sys_prepare_package_install

}




################################################################################
## Model
################################################################################

function model_prepare () {

	mod_prepare_package_install

}




################################################################################
## Portal
################################################################################

function portal_prepare () {

	model_prepare

}


################################################################################
## Main
################################################################################

function __main__ () {

	portal_prepare

}

__main__
