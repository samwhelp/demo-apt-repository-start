#!/usr/bin/env bash


################################################################################
## Environment
################################################################################

set -e						# exit on error
set -o pipefail				# exit on pipeline error
set -u						# treat unset variable as error


################################################################################
## Base Path
################################################################################

BASE_DIR_PATH="$(dirname "$(realpath "${0}")")"




################################################################################
## Init
################################################################################

source "${BASE_DIR_PATH}/init.sh"




################################################################################
## Module
################################################################################

function sys_apt_sources_list_remove () {

	local repo_sources_list_file_path="${REPO_SOURCES_LIST_FILE_PATH}"

	echo "sudo rm -f ${repo_sources_list_file_path}"
	sudo rm -f "${repo_sources_list_file_path}"

}

function mod_apt_sources_list_remove () {

	sys_apt_sources_list_remove

}




################################################################################
## Model
################################################################################

function model_apt_sources_list_remove () {

	mod_apt_sources_list_remove

}




################################################################################
## Portal
################################################################################

function portal_apt_sources_list_remove () {

	model_apt_sources_list_remove

}


################################################################################
## Main
################################################################################

function __main__ () {

	portal_apt_sources_list_remove

}

__main__
