#!/usr/bin/env bash


################################################################################
## Environment
################################################################################

set -e						# exit on error
set -o pipefail				# exit on pipeline error
set -u						# treat unset variable as error


################################################################################
## Base Path
################################################################################

BASE_DIR_PATH="$(dirname "$(realpath "${0}")")"




################################################################################
## Init
################################################################################

source "${BASE_DIR_PATH}/init.sh"




################################################################################
## Module
################################################################################

function sys_keyring_key_remove () {

	local repo_keyring_key_file_path="${REPO_KEYRING_KEY_FILE_PATH}"


	echo "sudo rm -rf ${repo_keyring_key_file_path}"
	echo
	sudo rm -rf "${repo_keyring_key_file_path}"

}

function mod_keyring_key_remove () {

	sys_keyring_key_remove

}




################################################################################
## Model
################################################################################

function model_keyring_key_remove () {

	mod_keyring_key_remove

}




################################################################################
## Portal
################################################################################

function portal_keyring_key_remove () {

	model_keyring_key_remove

}


################################################################################
## Main
################################################################################

function __main__ () {

	portal_keyring_key_remove

}

__main__
